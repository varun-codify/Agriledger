class I18nState(rx.State):
    """Internationalization state for multi-language support."""

    language: str = "English"

    @rx.var
    def t(self) -> dict[str, str]:
        """Return the translation dictionary for the current language."""
        return TRANSLATIONS.get(self.language, TRANSLATIONS["English"])

    @rx.event
    def set_language(self, lang: str):
        self.language = lang

    def translate(self, key: str) -> str:
        """Translate a key to the current language."""
        translations = TRANSLATIONS.get(self.language, TRANSLATIONS["English"])
        return translations.get(key, TRANSLATIONS["English"].get(key, key))
